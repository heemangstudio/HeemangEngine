//! Layout metrics of the faces Hancom ships, for laying out text set in
//! one of them when the face itself is missing.
//!
//! A table holds only what layout needs: the face's names, design em,
//! ascent and descent, and the advance width of every character it maps,
//! as runs of consecutive characters with one advance. No outlines, hints
//! or other font data: the glyphs come from the face drawing in its place
//! ([`crate::Face`] over an emulated backing). Runs span the characters a
//! face lacks between two of equal advance, so a table says nothing about
//! which characters the face maps. `data/hancom-metrics.bin` is
//! generated by `examples/metric_tables.rs` from Hancom's font files.
//!
//! File format (little endian): `HMMT` and a version byte, a `u16` table
//! count, then per table: a name count byte and that many names (a length
//! byte and UTF-8; the first is the name Hancom lists the face under), a flags byte (1 bold, 2 HFT), `u16` em, `i16` ascent,
//! `i16` descent, a varint run count and per run three varints: the gap
//! from the end of the previous run to its first character, its length and
//! its advance.

use std::collections::HashMap;
use std::sync::{Arc, OnceLock};

use crate::normalize;

static DATA: &[u8] = include_bytes!("../data/hancom-metrics.bin");

/// One face's layout metrics.
#[derive(Debug, PartialEq, Eq)]
pub struct MetricTable {
    pub names: Vec<String>,
    pub bold: bool,
    /// The face is an HFT face: Hancom widens its synthetic bold glyphs.
    pub hft: bool,
    pub em: u16,
    pub ascent: i32,
    pub descent: i32,
    /// `(first, last, advance)`, sorted and disjoint.
    runs: Vec<(u32, u32, u16)>,
}

impl MetricTable {
    pub fn new(
        names: Vec<String>,
        bold: bool,
        hft: bool,
        em: u16,
        ascent: i32,
        descent: i32,
        advances: &[(u32, u16)],
    ) -> MetricTable {
        let mut sorted = advances.to_vec();
        sorted.sort_unstable();
        let mut runs: Vec<(u32, u32, u16)> = Vec::new();
        for (c, a) in sorted {
            match runs.last_mut() {
                // A run spans characters the face lacks between two of the
                // same advance: layout asks only for characters the face
                // drawing in its place has.
                Some((_, last, adv)) if *adv == a => *last = c,
                _ => runs.push((c, c, a)),
            }
        }
        MetricTable {
            names,
            bold,
            hft,
            em,
            ascent,
            descent,
            runs,
        }
    }

    /// The name Hancom lists the face under: the first name.
    pub fn local(&self) -> &str {
        self.names.first().map_or("", String::as_str)
    }

    /// The advance of `ch` in design units, or `None` outside the runs.
    pub fn advance(&self, ch: char) -> Option<u16> {
        let c = ch as u32;
        let i = self.runs.partition_point(|r| r.1 < c);
        self.runs
            .get(i)
            .filter(|r| r.0 <= c)
            .map(|&(_, _, adv)| adv)
    }

    pub fn write(&self, out: &mut Vec<u8>) {
        out.push(self.names.len() as u8);
        for n in &self.names {
            out.push(n.len() as u8);
            out.extend_from_slice(n.as_bytes());
        }
        out.push(u8::from(self.bold) | u8::from(self.hft) << 1);
        out.extend_from_slice(&self.em.to_le_bytes());
        out.extend_from_slice(&(self.ascent as i16).to_le_bytes());
        out.extend_from_slice(&(self.descent as i16).to_le_bytes());
        varint(out, self.runs.len() as u32);
        let mut end = 0;
        for &(first, last, adv) in &self.runs {
            varint(out, first - end);
            varint(out, last - first + 1);
            varint(out, adv as u32);
            end = last + 1;
        }
    }
}

fn varint(out: &mut Vec<u8>, mut v: u32) {
    loop {
        let b = (v & 0x7F) as u8;
        v >>= 7;
        if v == 0 {
            out.push(b);
            return;
        }
        out.push(b | 0x80);
    }
}

struct Reader<'a>(&'a [u8]);

impl Reader<'_> {
    fn bytes(&mut self, n: usize) -> Option<&[u8]> {
        let (a, b) = self.0.split_at_checked(n)?;
        self.0 = b;
        Some(a)
    }
    fn u8(&mut self) -> Option<u8> {
        self.bytes(1).map(|b| b[0])
    }
    fn u16(&mut self) -> Option<u16> {
        self.bytes(2).map(|b| u16::from_le_bytes([b[0], b[1]]))
    }
    fn varint(&mut self) -> Option<u32> {
        let mut v = 0u32;
        for shift in (0..35).step_by(7) {
            let b = self.u8()?;
            v |= u32::from(b & 0x7F) << shift;
            if b & 0x80 == 0 {
                return Some(v);
            }
        }
        None
    }
}

/// Parses a metrics file; `None` when it is malformed.
pub fn parse(data: &[u8]) -> Option<Vec<MetricTable>> {
    let mut r = Reader(data);
    if r.bytes(4)? != b"HMMT" || r.u8()? != 1 {
        return None;
    }
    let count = r.u16()?;
    let mut out = Vec::with_capacity(count as usize);
    for _ in 0..count {
        let mut names = Vec::new();
        for _ in 0..r.u8()? {
            let n = r.u8()? as usize;
            names.push(String::from_utf8(r.bytes(n)?.to_vec()).ok()?);
        }
        let flags = r.u8()?;
        let em = r.u16()?;
        let ascent = r.u16()? as i16 as i32;
        let descent = r.u16()? as i16 as i32;
        let n = r.varint()?;
        let mut runs = Vec::with_capacity(n as usize);
        let mut end = 0u32;
        for _ in 0..n {
            let first = end.checked_add(r.varint()?)?;
            let len = r.varint()?;
            let adv = u16::try_from(r.varint()?).ok()?;
            let last = first.checked_add(len.checked_sub(1)?)?;
            runs.push((first, last, adv));
            end = last + 1;
        }
        out.push(MetricTable {
            names,
            bold: flags & 1 != 0,
            hft: flags & 2 != 0,
            em: em.max(1),
            ascent,
            descent,
            runs,
        });
    }
    Some(out)
}

/// Writes tables in the file format [`parse`] reads.
pub fn serialize(tables: &[MetricTable]) -> Vec<u8> {
    let mut out = b"HMMT\x01".to_vec();
    out.extend_from_slice(&(tables.len() as u16).to_le_bytes());
    for t in tables {
        t.write(&mut out);
    }
    out
}

/// The embedded tables by normalized face name.
pub(crate) struct Catalog {
    by_name: HashMap<String, Vec<Arc<MetricTable>>>,
}

impl Catalog {
    pub(crate) fn embedded() -> &'static Catalog {
        static CATALOG: OnceLock<Catalog> = OnceLock::new();
        CATALOG.get_or_init(|| {
            let mut by_name: HashMap<String, Vec<Arc<MetricTable>>> = HashMap::new();
            for t in parse(DATA).unwrap_or_default() {
                let t = Arc::new(t);
                for n in &t.names {
                    by_name.entry(normalize(n)).or_default().push(t.clone());
                }
            }
            Catalog { by_name }
        })
    }

    /// The table of face `name` for the weight asked for: its bold table
    /// when bold is asked for and Hancom has one, else its regular table.
    pub(crate) fn table(&self, name: &str, bold: bool) -> Option<&Arc<MetricTable>> {
        let list = self.by_name.get(&normalize(name))?;
        list.iter()
            .find(|t| t.bold == bold)
            .or_else(|| list.iter().find(|t| !t.bold))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_round_trip_and_look_up_runs() {
        let t = MetricTable::new(
            vec!["함초롬바탕".into(), "HCR Batang".into()],
            false,
            false,
            1000,
            800,
            200,
            &[
                (0x20, 300),
                (0x21, 300),
                (0x41, 650),
                (0xAC00, 970),
                (0xAC01, 970),
            ],
        );
        let back = parse(&serialize(std::slice::from_ref(&t))).unwrap();
        assert_eq!(back, vec![t]);
        let t = &back[0];
        assert_eq!(t.advance(' '), Some(300));
        assert_eq!(t.advance('!'), Some(300));
        assert_eq!(t.advance('"'), None);
        assert_eq!(t.advance('B'), None);
        assert_eq!(t.advance('A'), Some(650));
        assert_eq!(t.advance('각'), Some(970));
        assert_eq!(t.advance('갂'), None);
    }

    #[test]
    fn embedded_tables_parse() {
        assert!(parse(DATA).is_some());
    }
}
